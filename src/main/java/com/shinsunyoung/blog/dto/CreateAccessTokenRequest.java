// 이 파일이 하는 일
// ============================================================
// 새 액세스 토큰을 요청할 때, 사용자가 보내 준 리프레시 토큰을 담아 두는 그릇입니다.
// 이 객체 하나로 요청 데이터를 자바 코드에서 편하게 꺼내 쓸 수 있습니다.
//
// ============================================================
// DTO란?
// ============================================================
// DTO(Data Transfer Object)는 "데이터를 옮기기 위해 만든 객체"라는 뜻입니다.
// 화면이나 다른 프로그램에서 보낸 값을 자바 객체 안에 옮겨 담을 때 씁니다.
// 여기서 dto 폴더에 있는 클래스들은 모두 이런 역할을 합니다.
//
// ============================================================
// 실제 요청 모양 (이 객체로 바뀌는 데이터)
// ============================================================
// 사용자가 아래와 같은 내용을 보내면, 스프링이 자동으로 이 객체에 옮겨 담습니다.
//
//   {
//     "refreshToken": "eyJhbGciOiJIUzI1NiJ9.eyJzdWIiOi..."
//   }
//
// 여기서 "refreshToken" 이라는 이름이 아래 변수 이름과 같아야 옮겨 담기가 됩니다.

import lombok.Getter;
import lombok.Setter;

@Getter
@Setter
public class CreateAccessTokenRequest { //클래스 이름은 요청받은 리플러시 토큰으로  "액세스 토큰 생성 요청"이라는 뜻입니다.

    // 요청으로 받은 리프레시 토큰 문자열을 담는 변수입니다.
    // 요청 안의 "refreshToken" 항목 값이 여기에 들어갑니다.
    // 요청에 이 항목이 없으면 값은 null 입니다.
    private String refreshToken;


}
